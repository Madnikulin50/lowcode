/**
 * Rewrite generic Metric block help in generatedCatalog.js (no API/DB).
 *   node scripts/patch-metric-catalog.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { generateMetricBlockHelp, lookupMetricBlockArticle, HELP_MARK } from './lib/metric-help-articles-ru.mjs'

const CATALOG = join(dirname(fileURLToPath(import.meta.url)), '../client3/web/compose/src/help/generatedCatalog.js')
const GENERIC = 'Каждое число — агрегат по модулю'

function wrapHelp (body, title, pageTitle, nsName) {
  let text = String(body || '').replace(HELP_MARK, '').trim()
  text = text.replace(/^#\s+[^\n]+\n+/, '').trim()
  return `${HELP_MARK}\n**${title}.** ${text}\n\nСтраница: «${pageTitle}». Пространство: «${nsName}».`
}

const src = readFileSync(CATALOG, 'utf8')
const nsMatch = src.match(/export const GENERATED_NAMESPACE_DOCS = (\{[\s\S]*?\n\})\n\nexport const GENERATED_PAGE_DOCS/)
const pageMatch = src.match(/export const GENERATED_PAGE_DOCS = (\{[\s\S]*?\n\})\n\nexport const GENERATED_CHART_DOCS/)
const chartMatch = src.match(/export const GENERATED_CHART_DOCS = (\{[\s\S]*?\n\})\n\nexport const GENERATED_BLOCK_DOCS/)
const blockMatch = src.match(/export const GENERATED_BLOCK_DOCS = (\{[\s\S]*\})\n?\s*$/)
if (!nsMatch || !pageMatch || !chartMatch || !blockMatch) {
  throw new Error('Cannot parse generatedCatalog.js exports')
}

const nsDocs = JSON.parse(nsMatch[1])
const pageDocs = JSON.parse(pageMatch[1])
const chartDocs = JSON.parse(chartMatch[1])
const blockDocs = JSON.parse(blockMatch[1])

let n = 0
for (const [key, entry] of Object.entries(blockDocs)) {
  const help = String(entry?.help || '')
  const titleM = help.match(/\*\*(.+?)\.\*\*/)
  const pageM = help.match(/Страница: «([^»]+)»/)
  const nsM = help.match(/Пространство: «([^»]+)»/)
  if (!titleM) continue
  const looksMetric = help.includes(GENERIC) || help.includes('Блок показателей') ||
    help.includes('утреннего экрана') || help.includes('Показатели экрана') ||
    help.includes('Гигиена парка') || help.includes('Group procurement') ||
    help.includes('контура MinIO') || help.includes('Касса этой точки') ||
    help.includes('Четыре числа') || help.includes('Три числа') ||
    help.includes('Разрез модуля')
  const [slug, pageRef] = key.split('/')
  const title = titleM[1]
  const pageTitle = pageM?.[1] || pageRef
  const nsName = nsM?.[1] || slug
  if (!lookupMetricBlockArticle({ slug, pageHandle: pageRef, pageTitle, blockTitle: title })) continue
  if (!looksMetric && !help.includes(GENERIC)) {
    /* still refresh known metric articles to drop duplicate # headings */
  }
  const gen = generateMetricBlockHelp(
    { title, options: { metrics: [] } },
    { handle: pageRef, title: pageTitle },
    { slug, name: nsName },
    new Map(),
  )
  if (!gen?.help || gen.help.includes('Блок показателей')) continue
  entry.help = wrapHelp(gen.help, title, pageTitle, nsName)
  n++
}

writeFileSync(CATALOG, `/* generated by scripts/generate-extended-help.mjs — do not edit by hand */\n` +
  `export const GENERATED_NAMESPACE_DOCS = ${JSON.stringify(nsDocs, null, 2)}\n\n` +
  `export const GENERATED_PAGE_DOCS = ${JSON.stringify(pageDocs, null, 2)}\n\n` +
  `export const GENERATED_CHART_DOCS = ${JSON.stringify(chartDocs, null, 2)}\n\n` +
  `export const GENERATED_BLOCK_DOCS = ${JSON.stringify(blockDocs, null, 2)}\n`)

console.log('patched metric blocks', n)
