function words (text) {
  return String(text || '').replace(/[#*_`>[\]()]/g, ' ').split(/\s+/).filter(w => /[0-9A-Za-zА-Яа-яЁё]/.test(w)).length
}

function norm (s) {
  return String(s || '').trim().toLowerCase().replace(/\s+/g, ' ')
}

function expandTo (text, min, extras) {
  let out = String(text || '').trim()
  let i = 0
  while (words(out) < min && i < extras.length) {
    out += '\n\n' + extras[i]
    i++
  }
  return out.trim()
}

function reportOf (chart) {
  return (chart?.config?.reports || [])[0] || {}
}

function metricType (report) {
  return report.metrics?.[0]?.type || 'chart'
}

function dimField (report) {
  return report.dimensions?.[0]?.field || ''
}

function metricLabel (report) {
  const m = report.metrics?.[0] || {}
  return m.label || [m.aggregate, m.field].filter(Boolean).join(' ') || 'count'
}

