function loopTheme (name, moduleName) {
  const n = `${name} ${moduleName}`.toLowerCase()
  if (/incident|инцидент/.test(n)) return 'incidents'
  if (/margin|марж|прибыл|себестоим|валовая|выручка →/.test(n)) return 'margin'
  if (/stock|остат|заказ|doc|недосток|reorder|здоровье остат/.test(n)) return 'stock'
  if (/риск|risk/.test(n) && !/rfc/.test(n)) return 'risk'
  if (/hr|персонал|вакан|найм|стаж|отсут|численн|состав по статусу/.test(n)) return 'hr'
  if (/turn|оборач|doi|заморож|скорости/.test(n)) return 'turnover'
  if (/traffic|трафик/.test(n)) return 'traffic'
  if (/project|проект/.test(n)) return 'projects'
  if (/receipt|sales|выруч|чеков|transaction|продаж/.test(n)) return 'sales'
  if (/store type|типы магазин|еуые|perfomance|performance/.test(n)) return 'stores'
  if (/brand|category|категор|ассортимент|price of product|gauge/.test(n)) return 'products'
  return 'other'
}

