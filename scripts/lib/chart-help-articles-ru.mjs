export function lookupChartArticle ({ slug, handle, name }) {
  const keys = [
    `${slug}/${handle}`,
    `${slug}/${name}`,
    handle,
    name,
  ]
  for (const k of keys) {
    if (k && ARTICLES[k]) return ARTICLES[k]
    const nk = `${slug}/${norm(k)}`
    if (ARTICLES[nk]) return ARTICLES[nk]
  }
  return null
}

