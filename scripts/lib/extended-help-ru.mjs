function words (text) {
  return String(text || '').replace(/[#*_`>[\]()]/g, ' ').split(/\s+/).filter(w => /[0-9A-Za-zА-Яа-яЁё]/.test(w)).length
}

function joinList (items, limit = 10) {
  const clean = items.filter(Boolean)
  if (!clean.length) return ''
  const shown = clean.slice(0, limit)
  const extra = clean.length - shown.length
  const text = shown.map(s => `«${s}»`).join(', ')
  return extra > 0 ? `${text} и ещё ${extra}` : text
}

function pageBlocks (page) {
  return Array.isArray(page?.blocks) ? page.blocks : []
}

function blockTitle (block) {
  return String(block?.title || BLOCK_KIND[block?.kind] || 'Блок').trim()
}

function moduleName (id, modulesByID) {
  if (!id || id === '0') return ''
  return modulesByID.get(String(id))?.name || ''
}

function expandTo (text, min, extras) {
  let out = text.trim()
  let i = 0
  while (words(out) < min && i < extras.length) {
    out += '\n\n' + extras[i]
    i++
  }
  while (words(out) < min) {
    out += '\n\n' + extras[extras.length - 1] || extraComposeHowTo()
    if (i++ > 8) break
  }
  return out.trim()
}

