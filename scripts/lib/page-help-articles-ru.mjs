export function lookupPageArticle ({ slug, handle, title, moduleName, moduleHandle }) {
  const keys = [
    `${slug}/${handle}`,
    `${slug}/${norm(handle)}`,
    `${slug}/${norm(title)}`,
    `${slug}/${norm(moduleHandle)}`,
    `${slug}/${norm(moduleName)}`,
  ]
  for (const k of keys) {
    if (ARTICLES[k]) return ARTICLES[k]
    const alias = ALIASES[k]
    if (alias && ARTICLES[alias]) return ARTICLES[alias]
  }
  return null
}

