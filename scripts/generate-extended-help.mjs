#!/usr/bin/env node
/**
 * Write extended Russian help for every live Compose namespace, page, and block.
 *
 *   node scripts/generate-extended-help.mjs
 *   FORCE=1 node scripts/generate-extended-help.mjs
 *
 * Pages: >= 200 words. Charts: >= 100 words. Blocks: >= 50 words.
 * Page/namespace/chart help is also written to client3/web/compose/src/help/generatedCatalog.js
 * so the UI shows it even if the running API drops config.help.
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'
import { mintToken, detectBase, apiFactory, setOf } from '../agents/invest/compose/helpers.mjs'
import {
  HELP_MARK,
  generateNamespaceHelp,
  generatePageHelp,
  generateBlockHelp,
  generateChartHelp,
  wordCount,
} from './lib/extended-help-ru.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const FORCE = process.env.FORCE === '1' || process.argv.includes('--force')
const CATALOG = join(HERE, '../client3/web/compose/src/help/generatedCatalog.js')

const DSN_CANDIDATES = [...new Set([
  process.env.COMPOSE_DSN,
  'postgres://postgres:Zse45rdx@127.0.0.1:5432/test9?sslmode=disable',
  'postgres://postgres:Zse45rdx@127.0.0.1:5432/test10?sslmode=disable',
].filter(Boolean))]

function generated (v) {
  const s = String(v || '')
  return s.includes(HELP_MARK) || s.includes('<!-- compose-help:v1 -->')
}

function shouldWriteHelp (current) {
  if (FORCE) return true
  const s = String(current || '').trim()
  return !s || generated(s)
}

function psql (dsn, sql) {
  return execFileSync('psql', [dsn, '-v', 'ON_ERROR_STOP=1', '-tA', '-c', sql], { encoding: 'utf8' }).trim()
}

function sqlLiteral (value) {
  return `E'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

function detectDsn (namespaceID) {
  for (const dsn of DSN_CANDIDATES) {
    try {
      if (psql(dsn, `SELECT 1 FROM compose_namespace WHERE id = ${namespaceID} LIMIT 1`) === '1') return dsn
    } catch {}
  }
  throw new Error('Cannot find compose_namespace. Set COMPOSE_DSN.')
}

function mergeJsonb (dsn, table, id, column, patch) {
  const pairs = Object.entries(patch)
    .map(([k, v]) => `${sqlLiteral(k)}, to_jsonb(${sqlLiteral(v)}::text)`)
    .join(', ')
  psql(dsn, `
    UPDATE ${table}
    SET ${column} = COALESCE(${column}, '{}'::jsonb) || jsonb_build_object(${pairs})
    WHERE id = ${id}
  `)
}

function mergeChartConfigText (dsn, id, patch) {
  const pairs = Object.entries(patch)
    .map(([k, v]) => `${sqlLiteral(k)}, to_jsonb(${sqlLiteral(v)}::text)`)
    .join(', ')
  psql(dsn, `
    UPDATE compose_chart
    SET config = (
      CASE
        WHEN config IS NULL OR btrim(config) = '' THEN '{}'::jsonb
        ELSE config::jsonb
      END || jsonb_build_object(${pairs})
    )::text
    WHERE id = ${id}
  `)
}

function writeCatalog (pageDocs, nsDocs, chartDocs = {}, blockDocs = {}) {
  const body = `/* generated by scripts/generate-extended-help.mjs — do not edit by hand */\n` +
    `export const GENERATED_NAMESPACE_DOCS = ${JSON.stringify(nsDocs, null, 2)}\n\n` +
    `export const GENERATED_PAGE_DOCS = ${JSON.stringify(pageDocs, null, 2)}\n\n` +
    `export const GENERATED_CHART_DOCS = ${JSON.stringify(chartDocs, null, 2)}\n\n` +
    `export const GENERATED_BLOCK_DOCS = ${JSON.stringify(blockDocs, null, 2)}\n`
  writeFileSync(CATALOG, body)
}

async function main () {
  const token = await mintToken()
  const base = await detectBase(token)
  const api = apiFactory(base, token)
  const namespaces = setOf(await api('GET', '/namespace/?limit=500')).filter(n => !n.deletedAt)
  if (!namespaces.length) throw new Error('No namespaces')
  const dsn = detectDsn(namespaces[0].namespaceID)
  console.log('API', base)
  console.log('namespaces', namespaces.length)

  const pageDocs = {}
  const nsDocs = {}
  const chartDocs = {}
  const blockDocs = {}
  let pageN = 0
  let blockN = 0
  let chartN = 0
  let nsN = 0
  let shortPages = 0
  let shortBlocks = 0
  let shortCharts = 0

  for (const ns of namespaces) {
    const nsID = ns.namespaceID
    const [pages, charts, modules] = await Promise.all([
      api('GET', `/namespace/${nsID}/page/?limit=500`).then(setOf).then(s => s.filter(p => !p.deletedAt)),
      api('GET', `/namespace/${nsID}/chart/?limit=500`).then(setOf).then(s => s.filter(c => !c.deletedAt)),
      api('GET', `/namespace/${nsID}/module/?limit=500`).then(setOf).then(s => s.filter(m => !m.deletedAt)),
    ])
    const modulesByID = new Map(modules.map(m => [String(m.moduleID), m]))
    const chartsByID = new Map(charts.map(c => [String(c.chartID), c]))
    const slug = ns.slug || String(nsID)

    for (const page of pages) {
      const full = await api('GET', `/namespace/${nsID}/page/${page.pageID}`)
      const gen = generatePageHelp(full, ns, modulesByID, chartsByID)
      if (wordCount(gen.help) < 200) shortPages++
      const key = `${slug}/${page.handle || page.pageID}`
      pageDocs[key] = { description: gen.description, help: gen.help }
      if (page.handle && page.pageID) pageDocs[`${slug}/${page.pageID}`] = pageDocs[key]
      if (page.title && page.title !== page.handle) pageDocs[`${slug}/${page.title}`] = pageDocs[key]

      if (shouldWriteHelp(full.description) && gen.description !== full.description) {
        await api('POST', `/namespace/${nsID}/page/${page.pageID}`, {
          ...full,
          description: gen.description,
          updatedAt: full.updatedAt,
        })
      }
      if (shouldWriteHelp(full.config?.help)) {
        mergeJsonb(dsn, 'compose_page', page.pageID, 'config', { help: gen.help })
      }

      const blocks = Array.isArray(full.blocks) ? full.blocks : []
      let changed = false
      const nextBlocks = blocks.map(block => {
        const help = shouldWriteHelp(block.options?.help)
          ? generateBlockHelp(block, full, ns, modulesByID, chartsByID)
          : (block.options?.help || '')
        if (help) {
          const bkey = `${slug}/${page.handle || page.pageID}/${block.blockID}`
          blockDocs[bkey] = { help }
          if (page.pageID && page.handle) blockDocs[`${slug}/${page.pageID}/${block.blockID}`] = blockDocs[bkey]
        }
        if (!shouldWriteHelp(block.options?.help)) return block
        if (wordCount(help) < 50) shortBlocks++
        changed = true
        blockN++
        return { ...block, options: { ...(block.options || {}), help } }
      })
      if (changed) {
        const fresh = await api('GET', `/namespace/${nsID}/page/${page.pageID}`)
        await api('POST', `/namespace/${nsID}/page/${page.pageID}`, {
          ...fresh,
          description: gen.description || fresh.description,
          blocks: nextBlocks,
          updatedAt: fresh.updatedAt,
        })
      }
      pageN++
      console.log('  page', key, 'words', wordCount(gen.help), 'blocks', blocks.length)
    }

    for (const chart of charts) {
      const gen = generateChartHelp(chart, ns, modulesByID)
      if (wordCount(gen.help) < 100) shortCharts++
      const ckey = `${slug}/${chart.handle || chart.chartID}`
      chartDocs[ckey] = { description: gen.description, help: gen.help }
      if (chart.handle && chart.chartID) chartDocs[`${slug}/${chart.chartID}`] = chartDocs[ckey]
      if (chart.name && chart.name !== chart.handle) chartDocs[`${slug}/${chart.name}`] = chartDocs[ckey]
      if (shouldWriteHelp(chart.config?.help) || shouldWriteHelp(chart.config?.description)) {
        mergeChartConfigText(dsn, chart.chartID, { help: gen.help, description: gen.description })
        chartN++
      }
      console.log('  chart', ckey, 'words', wordCount(gen.help))
    }

    const genNs = generateNamespaceHelp(ns, pages, modules, charts)
    nsDocs[slug] = { hint: genNs.hint, description: genNs.description, help: genNs.help }
    if (shouldWriteHelp(ns.meta?.help)) {
      mergeJsonb(dsn, 'compose_namespace', nsID, 'meta', {
        help: genNs.help,
        subtitle: ns.meta?.subtitle || genNs.hint,
        description: ns.meta?.description || genNs.description,
      })
      nsN++
    }
    console.log('namespace', slug, 'words', wordCount(genNs.help))
  }

  writeCatalog(pageDocs, nsDocs, chartDocs, blockDocs)
  console.log(`done: namespaces ${nsN}, pages ${pageN}, blocks ${blockN}, charts ${chartN}`)
  if (shortPages || shortBlocks || shortCharts) {
    console.warn(`below minimum: pages ${shortPages}, blocks ${shortBlocks}, charts ${shortCharts}`)
  }
}

main().catch(err => {
  console.error(err)
  process.exit(1)
})
